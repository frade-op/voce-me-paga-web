const FIELD_LABELS_EN = {
  Quantidade: "Quantity",
  "Preço unitário": "Unit price",
  "Preço total": "Total price",
  "Total da nota": "Receipt total",
};

export function normalizeLanguage(value) {
  const code = String(value ?? "").slice(0, 2).toLowerCase();
  return LANGUAGES.includes(code) ? code : DEFAULT_LANGUAGE;
}

export function translate(language, key, params = {}) {
  const lang = normalizeLanguage(language);
  const template = MESSAGES[lang][key] ?? MESSAGES[DEFAULT_LANGUAGE][key] ?? key;
  return template.replace(/\{(\w+)\}/g, (match, name) => (name in params ? String(params[name]) : match));
}

export function translateError(language, message) {
  if (normalizeLanguage(language) === DEFAULT_LANGUAGE) return message;
  if (ERROR_MESSAGES_EN[message]) return ERROR_MESSAGES_EN[message];
  const invalid = /^(.+) inválido\.$/.exec(message);
  if (invalid) return `Invalid ${(FIELD_LABELS_EN[invalid[1]] ?? invalid[1]).toLowerCase()}.`;
  return message;
}

// A origem dos itens é guardada em português pelo domínio; traduz só na exibição.
export function translateSource(language, source) {
  if (source === "Manual") return translate(language, "source.manual");
  if (source === "Nota fiscal") return translate(language, "source.invoice");
  const match = /^Nota (.+)$/.exec(source ?? "");
  return match ? translate(language, "source.invoiceNumber", { number: match[1] }) : source;
}

export function detectLanguage(stored, navigatorLanguage) {
  if (stored && LANGUAGES.includes(stored)) return stored;
  return normalizeLanguage(navigatorLanguage);
}
